-- Mango System baseline schema.
-- Flyway owns DDL only. Required and demo data are registered under META-INF/mango.

CREATE TABLE IF NOT EXISTS `sys_dict_type` (
  `id` bigint NOT NULL COMMENT '主键',
  `dict_type` varchar(50) NOT NULL COMMENT '字典类型',
  `dict_name` varchar(100) NOT NULL COMMENT '字典名称',
  `domain_code` varchar(64) NOT NULL DEFAULT 'COMMON' COMMENT '业务域编码',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态：0-禁用 1-启用',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `tenant_id` varchar(64) NOT NULL DEFAULT 'default' COMMENT '租户标识',
  `org_id` bigint DEFAULT NULL COMMENT '组织 ID',
  `created_by` bigint DEFAULT NULL COMMENT '创建人 ID',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_by` bigint DEFAULT NULL COMMENT '更新人 ID',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_sys_dict_type_tenant_type` (`tenant_id`, `dict_type`),
  KEY `idx_sys_dict_type_domain` (`tenant_id`, `domain_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='字典类型表';

CREATE TABLE IF NOT EXISTS `sys_dict_data` (
  `id` bigint NOT NULL COMMENT '主键',
  `dict_type` varchar(50) NOT NULL COMMENT '字典类型',
  `dict_label` varchar(100) NOT NULL COMMENT '字典标签',
  `dict_value` varchar(100) NOT NULL COMMENT '字典值',
  `sort` int NOT NULL DEFAULT '0' COMMENT '排序号',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态：0-禁用 1-启用',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `tenant_id` varchar(64) NOT NULL DEFAULT 'default' COMMENT '租户标识',
  `org_id` bigint DEFAULT NULL COMMENT '组织 ID',
  `created_by` bigint DEFAULT NULL COMMENT '创建人 ID',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_by` bigint DEFAULT NULL COMMENT '更新人 ID',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_sys_dict_data_type` (`tenant_id`, `dict_type`),
  KEY `idx_sys_dict_data_value` (`tenant_id`, `dict_type`, `dict_value`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='字典数据表';

CREATE TABLE IF NOT EXISTS `sys_config` (
  `id` bigint NOT NULL COMMENT '主键',
  `config_key` varchar(100) NOT NULL COMMENT '配置键',
  `config_value` text NOT NULL COMMENT '配置值',
  `config_name` varchar(100) NOT NULL COMMENT '配置名称',
  `type` varchar(20) NOT NULL COMMENT '类型：SYSTEM/BUSINESS/SECURITY/FEATURE',
  `domain_code` varchar(64) NOT NULL DEFAULT 'COMMON' COMMENT '业务域编码',
  `value_type` varchar(32) DEFAULT 'STRING' COMMENT '配置值展示与编辑类型',
  `group_code` varchar(64) DEFAULT NULL COMMENT '配置分组编码',
  `group_name` varchar(100) DEFAULT NULL COMMENT '配置分组名称',
  `default_value` text DEFAULT NULL COMMENT '默认值',
  `options` text DEFAULT NULL COMMENT '选项列表 JSON',
  `option_source` varchar(32) NOT NULL DEFAULT 'CUSTOM' COMMENT '选项来源：CUSTOM/DICT',
  `dict_type` varchar(50) DEFAULT NULL COMMENT '绑定字典类型',
  `editable` tinyint NOT NULL DEFAULT '1' COMMENT '是否可编辑：0-否 1-是',
  `editable_reason` varchar(200) DEFAULT NULL COMMENT '不可编辑原因',
  `sort` int NOT NULL DEFAULT '0' COMMENT '排序号',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态：0-禁用 1-启用',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `tenant_id` varchar(64) NOT NULL DEFAULT 'default' COMMENT '租户标识',
  `org_id` bigint DEFAULT NULL COMMENT '组织 ID',
  `created_by` bigint DEFAULT NULL COMMENT '创建人 ID',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_by` bigint DEFAULT NULL COMMENT '更新人 ID',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_sys_config_tenant_key` (`tenant_id`, `config_key`),
  KEY `idx_sys_config_type` (`tenant_id`, `type`),
  KEY `idx_sys_config_domain` (`tenant_id`, `domain_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='系统配置表';

