CREATE TABLE IF NOT EXISTS `integration_connector` (
    `id` bigint NOT NULL COMMENT '主键',
    `tenant_id` varchar(64) NOT NULL DEFAULT 'default' COMMENT '租户标识',
    `org_id` bigint DEFAULT NULL COMMENT '组织标识',
    `connector_code` varchar(64) NOT NULL COMMENT '连接器编码',
    `connector_name` varchar(100) NOT NULL COMMENT '连接器名称',
    `category` varchar(32) DEFAULT NULL COMMENT '用途分类，字典 integration_connector_category',
    `provider` varchar(64) DEFAULT NULL COMMENT '厂商标识',
    `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态：0-停用，1-启用',
    `config_schema` text COMMENT '配置规范JSON Schema',
    `auth_schema` text COMMENT '认证规范JSON',
    `capabilities_json` text COMMENT '能力清单JSON',
    `tags` varchar(255) DEFAULT NULL COMMENT '标签，逗号分隔',
    `docs_url` varchar(500) DEFAULT NULL COMMENT '文档地址',
    `created_by` bigint DEFAULT NULL COMMENT '创建人',
    `created_at` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_by` bigint DEFAULT NULL COMMENT '更新人',
    `updated_at` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_integration_connector_code` (`connector_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='集成连接器定义';

CREATE TABLE IF NOT EXISTS `integration_credential` (
    `id` bigint NOT NULL COMMENT '主键',
    `tenant_id` varchar(64) NOT NULL DEFAULT 'default' COMMENT '租户标识',
    `org_id` bigint DEFAULT NULL COMMENT '组织标识',
    `credential_code` varchar(64) NOT NULL COMMENT '凭证编码',
    `connector_code` varchar(64) NOT NULL COMMENT '连接器编码',
    `fields_json` text COMMENT '凭证字段JSON，敏感字段为密文',
    `field_versions_json` text COMMENT '敏感字段版本JSON',
    `rotated_at` datetime DEFAULT NULL COMMENT '最近轮换时间',
    `expires_at` datetime DEFAULT NULL COMMENT '到期时间',
    `status` varchar(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态：ACTIVE/ROTATING/EXPIRED',
    `remark` varchar(500) DEFAULT NULL COMMENT '备注',
    `created_by` bigint DEFAULT NULL COMMENT '创建人',
    `created_at` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_by` bigint DEFAULT NULL COMMENT '更新人',
    `updated_at` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_integration_credential_code` (`tenant_id`, `credential_code`),
    KEY `idx_integration_credential_connector` (`connector_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='集成凭证';

CREATE TABLE IF NOT EXISTS `integration_instance` (
    `id` bigint NOT NULL COMMENT '主键',
    `tenant_id` varchar(64) NOT NULL DEFAULT 'default' COMMENT '租户标识',
    `org_id` bigint DEFAULT NULL COMMENT '组织标识',
    `instance_code` varchar(64) NOT NULL COMMENT '实例编码',
    `instance_name` varchar(100) NOT NULL COMMENT '实例名称',
    `connector_code` varchar(64) NOT NULL COMMENT '连接器编码',
    `environment` varchar(16) NOT NULL DEFAULT 'PROD' COMMENT '环境：PROD/TEST',
    `config_values_json` text COMMENT '配置值JSON',
    `credential_code` varchar(64) DEFAULT NULL COMMENT '凭证编码',
    `capabilities_json` varchar(2048) DEFAULT NULL COMMENT '已授权能力',
    `status` tinyint NOT NULL DEFAULT 0 COMMENT '状态：0-停用，1-启用',
    `owner` varchar(64) DEFAULT NULL COMMENT '责任人',
    `remark` varchar(500) DEFAULT NULL COMMENT '备注',
    `created_by` bigint DEFAULT NULL COMMENT '创建人',
    `created_at` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_by` bigint DEFAULT NULL COMMENT '更新人',
    `updated_at` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_integration_instance_code` (`tenant_id`, `instance_code`),
    KEY `idx_integration_instance_connector` (`connector_code`),
    KEY `idx_integration_instance_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='集成连接实例';
