  KEY `idx_file_object` (`bucket_name`,`object_name`),
  KEY `idx_file_tenant` (`tenant_id`),
  KEY `idx_file_biz` (`tenant_id`,`biz_type`,`biz_id`),
  KEY `idx_file_purpose` (`tenant_id`,`purpose`),
  KEY `idx_file_record_object_id` (`object_id`),
  KEY `idx_file_status` (`tenant_id`,`status`,`archived`),
  KEY `idx_file_directory` (`tenant_id`,`directory_id`,`archived`,`created_time`),
  KEY `idx_file_created_time` (`created_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='文件记录表';

