  `file_size` bigint NOT NULL DEFAULT '0' COMMENT '文件大小',
  `content_type` varchar(128) DEFAULT NULL COMMENT '内容类型',
  `file_hash` varchar(128) DEFAULT NULL COMMENT '文件哈希',
