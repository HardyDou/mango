-- File module baseline for a fresh database. Flyway owns DDL only.

CREATE TABLE `file_storage_config` (
  `id` bigint NOT NULL COMMENT '存储配置ID',
  `tenant_id` bigint NOT NULL DEFAULT '1' COMMENT '租户ID',
  `org_id` bigint DEFAULT NULL COMMENT '组织ID',
  `config_name` varchar(64) NOT NULL COMMENT '配置名称',
  `storage_type` varchar(32) NOT NULL COMMENT '存储类型',
  `endpoint` varchar(255) DEFAULT NULL COMMENT '接入地址',
  `public_endpoint` varchar(255) DEFAULT NULL COMMENT '公开访问地址',
  `region` varchar(64) DEFAULT NULL COMMENT '区域',
  `bucket_name` varchar(128) NOT NULL COMMENT '存储桶名称',
  `storage_path` varchar(255) NOT NULL DEFAULT '' COMMENT '存储路径前缀',
  `access_key` varchar(255) DEFAULT NULL COMMENT '访问密钥AccessKey',
  `secret_key` varchar(512) DEFAULT NULL COMMENT '访问密钥SecretKey',
  `path_style_access` tinyint NOT NULL DEFAULT '0' COMMENT '是否使用Path Style访问',
  `ssl_enabled` tinyint NOT NULL DEFAULT '0' COMMENT '是否启用HTTPS',
  `active` tinyint NOT NULL DEFAULT '0' COMMENT '是否默认启用',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态',
  `remark` varchar(255) DEFAULT NULL COMMENT '备注',
  `created_by` bigint DEFAULT NULL COMMENT '创建人ID',
  `created_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '兼容创建时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '标准创建时间',
  `updated_by` bigint DEFAULT NULL COMMENT '更新人ID',
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '兼容更新时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '标准更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_file_storage_config_name` (`tenant_id`,`config_name`),
  KEY `idx_file_storage_type` (`storage_type`),
  KEY `idx_file_storage_active` (`tenant_id`,`active`,`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='文件存储配置表';

CREATE TABLE `file_settings` (
  `id` bigint NOT NULL COMMENT '文件中心配置ID',
  `tenant_id` bigint NOT NULL DEFAULT '1' COMMENT '租户ID',
  `org_id` bigint DEFAULT NULL COMMENT '组织ID',
  `max_size` bigint NOT NULL DEFAULT '104857600' COMMENT '单文件最大大小',
  `allowed_extensions` varchar(1000) DEFAULT NULL COMMENT '允许上传扩展名',
  `blocked_extensions` varchar(1000) DEFAULT 'exe,bat,cmd,sh,jar' COMMENT '禁止上传扩展名',
  `default_access_level` varchar(32) NOT NULL DEFAULT 'PRIVATE' COMMENT '默认访问级别',
  `duplicate_name_strategy` varchar(32) NOT NULL DEFAULT 'AUTO_RENAME' COMMENT '重名处理策略',
  `duplicate_check_directory_scoped` tinyint NOT NULL DEFAULT '1' COMMENT '是否按目录隔离重名',
  `object_name_strategy` varchar(32) NOT NULL DEFAULT 'DATE_UUID' COMMENT '对象命名策略',
  `instant_upload_enabled` tinyint NOT NULL DEFAULT '1' COMMENT '是否启用秒传',
  `instant_upload_scope` varchar(32) NOT NULL DEFAULT 'TENANT' COMMENT '秒传匹配范围',
  `content_type_check_enabled` tinyint NOT NULL DEFAULT '1' COMMENT '是否校验内容类型',
  `allowed_content_types` varchar(1000) DEFAULT NULL COMMENT '允许上传内容类型',
  `blocked_content_types` varchar(1000) DEFAULT 'application/x-msdownload,application/x-sh' COMMENT '禁止上传内容类型',
  `direct_upload_enabled` tinyint NOT NULL DEFAULT '0' COMMENT '是否启用客户端直传',
  `direct_upload_expire_seconds` bigint NOT NULL DEFAULT '900' COMMENT '直传签名有效期',
  `access_token_enabled` tinyint NOT NULL DEFAULT '1' COMMENT '是否启用访问令牌',
  `public_read_requires_token` tinyint NOT NULL DEFAULT '1' COMMENT '公开文件是否需要令牌',
  `access_mode` varchar(32) NOT NULL DEFAULT 'DIRECT' COMMENT '文件访问模式',
  `access_token_expire_seconds` bigint NOT NULL DEFAULT '86400' COMMENT '访问令牌有效期',
  `preview_provider_url` varchar(500) DEFAULT '/file-preview/files/preview' COMMENT '外部文档预览地址',
  `preview_expire_seconds` bigint NOT NULL DEFAULT '86400' COMMENT '预览访问有效期',
  `preview_external_extensions` varchar(1000) DEFAULT 'txt,csv,json,xml,png,jpg,jpeg,gif,webp,svg,pdf,ofd,doc,docx,xls,xlsx,ppt,pptx,odt,ods,odp,zip,rar,7z' COMMENT '外部预览扩展名',
  `archive_retain_enabled` tinyint NOT NULL DEFAULT '1' COMMENT '是否保留归档记录',
  `archive_retain_days` int NOT NULL DEFAULT '180' COMMENT '归档记录保留天数',
  `archive_restore_enabled` tinyint NOT NULL DEFAULT '0' COMMENT '是否允许恢复归档',
  `physical_delete_enabled` tinyint NOT NULL DEFAULT '0' COMMENT '是否删除物理对象',
  `created_by` bigint DEFAULT NULL COMMENT '创建人ID',
  `created_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '兼容创建时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '标准创建时间',
  `updated_by` bigint DEFAULT NULL COMMENT '更新人ID',
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '兼容更新时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '标准更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_file_settings_tenant` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='文件中心运行时配置表';

CREATE TABLE `file_directory` (
  `id` bigint NOT NULL COMMENT '目录ID',
  `tenant_id` bigint NOT NULL COMMENT '租户ID',
  `org_id` bigint DEFAULT NULL COMMENT '组织ID',
  `parent_id` bigint NOT NULL DEFAULT '0' COMMENT '父目录ID',
  `directory_name` varchar(128) NOT NULL COMMENT '目录名称',
  `directory_path` varchar(1000) NOT NULL DEFAULT '/' COMMENT '目录路径',
  `sort` int NOT NULL DEFAULT '0' COMMENT '排序值',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态',
  `created_by` bigint DEFAULT NULL COMMENT '创建人ID',
  `created_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '兼容创建时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '标准创建时间',
  `updated_by` bigint DEFAULT NULL COMMENT '更新人ID',
  `updated_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '兼容更新时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '标准更新时间',
